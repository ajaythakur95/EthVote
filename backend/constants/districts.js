const normalizeDistrict = (value = "") => value.trim().toLowerCase();
const resolveDistrict = (value = "") => {
  const trimmed = value.trim();
  if (!trimmed) return "";
  const normalized = normalizeDistrict(value);
  return DISTRICTS.find((district) => normalizeDistrict(district) === normalized) || trimmed;
};

module.exports = { DISTRICTS, normalizeDistrict, resolveDistrict };
